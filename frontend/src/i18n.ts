const detector = new LanguageDetector()
detector.addDetector({
  name: 'cookieLang',
  lookup() {
    return Cookies.get('lang')
  },
  cacheUserLanguage(lng) {
    Cookies.set('lang', lng, { expires: 365 })
  }
})

i18n
  .use(detector)
  .use(initReactI18next)
  .init({
    resources,
    fallbackLng: 'en',
    detection: {
      order: ['cookieLang', 'navigator'],
      caches: ['cookieLang'],
    },
    interpolation: {
      escapeValue: false
    }
  })

// Custom logic for initial set
const currentLang = Cookies.get('lang')
if (!currentLang) {
  const browserLang = (navigator.language || '').toLowerCase()
  let langToSet = 'en'
  if (browserLang.startsWith('ru')) langToSet = 'ru'
  else if (browserLang.startsWith('ro')) langToSet = 'ro'
  
  i18n.changeLanguage(langToSet)
  Cookies.set('lang', langToSet, { expires: 365 })
}

export default i18n
